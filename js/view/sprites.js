export function crearSprite(mapa, color) {
  const lienzo = document.createElement('canvas');
  lienzo.width = mapa[0].length;
  lienzo.height = mapa.length;
  const ctx = lienzo.getContext('2d');
  ctx.fillStyle = color;
  mapa.forEach((fila, y) => {
    [...fila].forEach((punto, x) => {
      if (punto === '#') ctx.fillRect(x, y, 1, 1);
    });
  });
  return lienzo;
}
